// Lightweight i18n. English is the fallback; every other language may cover a
// subset of keys. The app's high-traffic chrome (tabs, settings sections,
// common actions) is translated; long explanatory sentences stay English for
// now and can be added key-by-key without touching components.
//
// RTL: Arabic sets I18nManager.forceRTL on the next launch (Android requires a
// restart to re-lay-out native views).

export type LanguageCode = "system" | "en" | "hi" | "ml" | "de" | "es" | "ar";

export const LANGUAGES: { key: LanguageCode; label: string; native: string }[] = [
  { key: "system", label: "System", native: "System" },
  { key: "en", label: "English", native: "English" },
  { key: "hi", label: "Hindi", native: "हिन्दी" },
  { key: "ml", label: "Malayalam", native: "മലയാളം" },
  { key: "de", label: "German", native: "Deutsch" },
  { key: "es", label: "Spanish", native: "Español" },
  { key: "ar", label: "Arabic", native: "العربية" },
];

export function isRTLLanguage(lang: string): boolean {
  return lang === "ar";
}

export function systemLanguage(): LanguageCode {
  try {
    const locale =
      (Intl as any)?.DateTimeFormat?.().resolvedOptions?.().locale ?? "en";
    const base = String(locale).split("-")[0].toLowerCase();
    if (["en", "hi", "ml", "de", "es", "ar"].includes(base)) return base as LanguageCode;
  } catch {}
  return "en";
}

export function resolveLanguage(pref: string): Exclude<LanguageCode, "system"> {
  if (pref === "system") return systemLanguage() as Exclude<LanguageCode, "system">;
  return (pref as Exclude<LanguageCode, "system">) || "en";
}


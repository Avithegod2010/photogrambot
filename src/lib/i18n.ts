const DICTS: Record<string, Dict> = { en, hi, ml, de, es, ar };

export function t(key: string, lang: string, vars?: Record<string, string>): string {
  const resolved = resolveLanguage(lang);
  const raw = DICTS[resolved]?.[key] ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? `{${name}}`);
}

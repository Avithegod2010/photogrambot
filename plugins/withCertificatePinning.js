// Expo config plugin: Android certificate pinning for api.telegram.org and
// api.github.com.
//
// The pins are SHA-256 SPKI hashes of the current leaf + intermediate + root
// certificates (any one matching keeps the connection alive). Include the
// intermediate/root so a routine leaf renewal does not brick the app. Refresh
// the leaf pin when the certificate rotates (see docs/SECURITY.md).
//
// This is deliberately a static network-security-config: Android applies it
// before any JavaScript runs, so it also covers native/background traffic.

const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

const PINS = {
  "api.telegram.org": [
    // leaf: *.telegram.org via Go Daddy Secure Certificate Authority - G2
    "AgyCmTysFOI6aQCSyQJ+QIXpnGn0v7n+D+mv6jWAtQc=",
    // intermediate: Go Daddy Secure Certificate Authority - G2
    "8Rw90Ej3Ttt8RRkrg+WYDS9n7IS03bk5bjP/UXPtaY8=",
    // root: Go Daddy Root Certificate Authority - G2
    "Ko8tivDrEjiY90yGasP6ZpBU4jwXvHqVvQI0GS3GNdA=",
  ],
  "api.github.com": [
    // leaf: *.github.com via Sectigo Public Server Authentication CA DV E36
    "nTvjJtN51Jp5ounTgUohZxRsHH5DUHgGorVUZyBxrAM=",
    // intermediate: Sectigo Public Server Authentication CA DV E36
    "VqePxH3EcFwZuYK3CCOMz5HKMoeIZpZcEyBf4diPGSA=",
    // root: Sectigo Public Server Authentication Root E46
    "EdsvlytFf4a/O+hCPwBXFFi46RKXqivCAF+mO7s+5Ng=",
    // backup root: USERTrust ECC Certification Authority
    "UJM2FOhG9aTNY0Pg4hgqjNzZ/lQBiMGRxPD5Y2/e0bw=",
  ],
};

function networkSecurityXml() {
  const domains = Object.entries(PINS)
    .map(([host, pins]) => {
      const pinTags = pins.map((p) => `      <pin digest="SHA-256">${p}</pin>`).join("\n");
      return `  <domain-config cleartextTrafficPermitted="false">\n    <domain includeSubdomains="false">${host}</domain>\n    <pin-set>\n${pinTags}\n    </pin-set>\n  </domain-config>`;
    })
    .join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by plugins/withCertificatePinning.js - do not hand-edit pins. -->\n<network-security-config>\n${domains}\n</network-security-config>\n`;
}

function withPinning(config) {
  config = withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (app) {
      app.$ = app.$ ?? {};
      app.$["android:networkSecurityConfig"] = "@xml/network_security_config";
      app.$["android:usesCleartextTraffic"] = "false";
    }
    return cfg;
  });
  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "res", "xml");
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, "network_security_config.xml"), networkSecurityXml());
      // Debug builds keep cleartext for Metro/dev-client connections.
      const debugDir = path.join(
        cfg.modRequest.platformProjectRoot,
        "app",
        "src",
        "debug",
        "res",
        "xml"
      );
      fs.mkdirSync(debugDir, { recursive: true });
      fs.writeFileSync(
        path.join(debugDir, "network_security_config.xml"),
        '<?xml version="1.0" encoding="utf-8"?>\n<network-security-config>\n  <base-config cleartextTrafficPermitted="true" />\n</network-security-config>\n'
      );
      return cfg;
    },
  ]);
  return config;
}

module.exports = withPinning;
